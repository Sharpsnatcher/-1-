# Дни недели по порядку, номера от 0 до 10
days = ["перводневник", "трудник", "маленькопятница", "постработник",
        "отдыхатница", "приветник", "дружник", "семейник",
        "радостник", "отсыпальник", "релаксенье"]
# Спрашиваем у пользователя сегодняшний день
today = input("Какой сегодня день? ")
# Проверяем, есть ли такой день в списке
if today in days:
    # Номер сегодняшнего дня в списке
    today_number = days.index(today)
    # Берём остаток от деления на 11
    answer = (today_number + 10522) % 11
    print("Через 10522 дня будет день номер", answer, "-", days[answer])
else:
    print("Ошибка: такого дня нет на Питонии")
